// The transaction owns allocation and insertion. A permanent reservation protects deleted/retired codes.
export async function allocateEmployeeCode(tx, tenantId, category) {
  if (!tenantId) fail("Verified company is required");
  EmploymentCategory.parse(category);
  const prefix = CATEGORY_PREFIX[category];
  await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${tenantId + ":employee-code:" + prefix},0))`;
  const config = (await tx.employeeCodeConfiguration.findUnique({
    where: { tenantId },
  })) || { padding: 4, separator: "-" };
  const seq = await tx.employeeCodeSequence.upsert({
    where: { tenantId_prefix: { tenantId, prefix } },
    create: { tenantId, prefix, lastValue: 0 },
    update: {},
  });
  // Initialize above every retained prefix number, including legacy padding formats.
  const legacy = await tx.employeeCodeReservation.findMany({
    where: { tenantId, employeeCode: { startsWith: prefix } },
    select: { employeeCode: true },
  });
  let n = seq.lastValue;
  const retained = await tx.employee.findMany({
    where: { tenant_id: tenantId, employee_code: { startsWith: prefix } },
    select: { employee_code: true },
  });
  for (const item of [
    ...legacy,
    ...retained.map((e) => ({ employeeCode: e.employee_code })),
  ]) {
    const match = item.employeeCode.match(new RegExp(`^${prefix}[-_]?(\\d+)$`));
    if (match && BigInt(match[1]) > n) n = BigInt(match[1]);
  }
  for (let attempt = 0; attempt < 10000; attempt++) {
    n++;
    const code = formatEmployeeCode(category, n, config);
    if (
      await tx.employeeCodeReservation.findFirst({
        where: { tenantId, collisionKey: collisionKey(code) },
      })
    )
      continue;
    if (
      await tx.employee.findFirst({
        where: { tenant_id: tenantId, employee_code: code },
        select: { id: true },
      })
    )
      continue;
    await tx.employeeCodeSequence.update({
      where: { tenantId_prefix: { tenantId, prefix } },
      data: { lastValue: n, version: { increment: 1 } },
    });
    // The insertion trigger reserves the code. Reserving here would consume it twice.
    return code;
  }
  fail("Employee code allocation needs HR review", 409);
}
export async function prepareEmployeeInsert(
  tx,
  data,
  { tenantId, category } = {},
) {
  if (data.employee_code)
    fail(
      "New employee codes are generated by the server; leave the code blank",
    );
  return {
    ...data,
    tenant_id: tenantId,
    employeeCategory: EmploymentCategory.parse(category),
    employee_code: await allocateEmployeeCode(tx, tenantId, category),
  };
}
export function guardIdentityEdit(existing, data) {
  const code = data.employeeCode ?? data.employee_code;
  if (
    code !== undefined &&
    canonicalEmployeeCode(code) !== existing.employee_code
  )
    fail(
      "Use the approved employee-code correction or category conversion action",
      409,
    );
  if (
    data.employeeCategory !== undefined &&
    data.employeeCategory !== existing.employeeCategory
  )
    fail("Category changes require the approved conversion action", 409);
  if (!existing.employee_code?.trim())
    fail("Resolve the missing employee code before activation or editing", 409);
}
export const configureEmployeeCode = (raw) => {
  const input = CodeConfiguration.parse(raw);
  return run(
    input,
    "hr.employee_code.manage",
    async (tx, env) => {
      if (input.employeeCode !== env.who.employee_code)
        fail("Configuration actor must be your employee code", 403);
      await tx.$executeRaw`SELECT pg_advisory_xact_lock(hashtextextended(${env.tenantId + ":code-format"},0))`;
      const old = await tx.employeeCodeConfiguration.findUnique({
        where: { tenantId: env.tenantId },
      });
      checkVersion(old || { version: 0 }, input.expectedVersion);
      const row = await tx.employeeCodeConfiguration.upsert({
        where: { tenantId: env.tenantId },
        create: {
          tenantId: env.tenantId,
          ...input.format,
          actorCode: env.who.employee_code,
        },
        update: {
          ...input.format,
          actorCode: env.who.employee_code,
          version: { increment: 1 },
        },
      });
      return result(env, view(row, "CODE_FORMAT", input.format));
    },
    "CODE_FORMAT",
  );
};

// Shared with the existing approved correction tool. Frozen evidence/signatures retain their original code.
export async function propagateEmployeeCode(
  tx,
  {
    tenantId,
    oldCode,
    newCode,
    actorCode,
    reason,
    effectiveAt,
    conversionRef = null,
  },
) {
  const current = await employee(tx, tenantId, oldCode);
  const correction = await tx.assessmentCodeChange.create({
    data: { tenantId, oldCode, newCode, approvedByCode: actorCode, reason },
  });
  await tx.employeeCodeAlias.create({
    data: {
      tenantId,
      employeeCode: oldCode,
      newCode,
      effectiveAt,
      reason,
      actorCode,
      conversionRef,
    },
  });
  await tx.$executeRaw`SELECT set_config('app.assessment_code_change', ${correction.id}, true)`;
  if (conversionRef)
    await tx.$executeRaw`SELECT set_config('app.employee_category_conversion', ${conversionRef}, true)`;
  await tx.employee.update({
    where: { id: current.id },
    data: { employee_code: newCode, version: { increment: 1 } },
  });
  await tx.assessmentIdentity.updateMany({
    where: { tenantId, employeeCode: oldCode },
    data: { employeeCode: newCode },
  });
  await tx.assessmentIdentity.updateMany({
    where: { tenantId, managerCode: oldCode },
    data: { managerCode: newCode },
  });
  // Re-key current adapter deduplication keys as well as employee columns.
  // Published revisions and appraisal inputs remain under the original code.
  const referenceFields = [
    "employeeCode",
    "managerCode",
    "raterCode",
    "reviewerCode",
  ];
  const integrations = await tx.assessmentIntegration.findMany({
    where: {
      tenantId,
      OR: [
        { employeeCode: oldCode },
        ...referenceFields.map((field) => ({
          payload: { path: [field], equals: oldCode },
        })),
      ],
    },
  });
  for (const integration of integrations) {
    const payload = { ...integration.payload };
    for (const field of referenceFields)
      if (payload[field] === oldCode) payload[field] = newCode;
    let key = integration.key;
    if (integration.kind === "DEVELOPMENT" && key.startsWith(oldCode + ":"))
      key = newCode + key.slice(oldCode.length);
    if (integration.kind === "ACTIVE_PROFILE" && key === oldCode) key = newCode;
    await tx.assessmentIntegration.update({
      where: { id: integration.id },
      data: { key, payload, sequence: { increment: 1 } },
    });
  }
  for (const table of [
    "employeeAssessmentProfile",
    "assessmentQualification",
    "assessmentCapability",
    "assessmentRestriction",
    "assessmentIntegration",
    "assessmentNotification",
  ])
    await tx[table].updateMany({
      where: { tenantId, employeeCode: oldCode },
      data: { employeeCode: newCode },
    });
  const closed = ["PUBLISHED", "REVOKED", "SUPERSEDED", "CLOSED_INCOMPLETE"];
  await tx.assessmentAssignment.updateMany({
    where: { tenantId, employeeCode: oldCode, state: { notIn: closed } },
    data: { state: "CLOSED_INCOMPLETE", version: { increment: 1 } },
  });
  for (const field of ["raterCode", "reviewerCode"])
    await tx.assessmentAssignment.updateMany({
      where: { tenantId, [field]: oldCode, state: { notIn: closed } },
      data: { [field]: newCode, version: { increment: 1 } },
    });
  const open = await tx.separation.findMany({
    where: {
      tenantId,
      employeeCode: oldCode,
      state: { notIn: ["EXIT_COMPLETED", "WITHDRAWN", "CANCELLED"] },
    },
    select: { id: true },
  });
  for (const s of open) {
    await tx.separation.update({
      where: { id: s.id },
      data: { employeeCode: newCode, version: { increment: 1 } },
    });
    for (const table of [
      "noticePeriodRecord",
      "replacementPlan",
      "replacementSession",
      "knowledgeTransferItem",
      "assetHandoverItem",
      "accessRevocationTask",
      "clearanceItem",
      "exitInterview",
      "finalSettlementSheet",
      "separationSourceSnapshot",
    ])
      await tx[table].updateMany({
        where: { tenantId, separationRef: s.id },
        data: { employeeCode: newCode, version: { increment: 1 } },
      });
  }
  await tx.separation.updateMany({
    where: {
      tenantId,
      managerCode: oldCode,
      state: { notIn: ["EXIT_COMPLETED", "WITHDRAWN", "CANCELLED"] },
    },
    data: { managerCode: newCode, version: { increment: 1 } },
  });
  for (const table of [
    "replacementPlan",
    "replacementSession",
    "knowledgeTransferItem",
    "assetHandoverItem",
    "accessRevocationTask",
    "clearanceItem",
    "finalSettlementSheet",
  ])
    await tx[table].updateMany({
      where: { tenantId, ownerCode: oldCode, status: { not: "COMPLETED" } },
      data: { ownerCode: newCode, version: { increment: 1 } },
    });
  for (const d of await tx.employmentDelivery.findMany({
    where: { tenantId, state: { in: ["PENDING", "RETRY"] } },
  })) {
    const payload = { ...d.payload };
    let changed = false;
    if (payload.recipientCodes?.includes(oldCode)) {
      payload.recipientCodes = payload.recipientCodes.map((c) =>
        c === oldCode ? newCode : c,
      );
      changed = true;
    }
    if (d.employeeCode === oldCode || changed)
      await tx.employmentDelivery.update({
        where: { id: d.id },
        data: {
          employeeCode: d.employeeCode === oldCode ? newCode : d.employeeCode,
          payload,
          version: { increment: 1 },
        },
      });
  }
  await tx.employeeCategoryConversion.updateMany({
    where: {
      tenantId,
      employeeCode: oldCode,
      state: { in: ["REQUESTED", "APPROVED"] },
    },
    data: { employeeCode: newCode, version: { increment: 1 } },
  });
  const queued = await enqueueHrDomainEvent(tx, {
    eventName: "hr.employee.code_changed.v1",
    tenantId,
    actorId: actorCode,
    actorType: "user",
    aggregateType: "EmployeeCode",
    aggregateId: correction.id,
    payload: json({ oldCode, newCode, changeRef: correction.id, effectiveAt }),
  });
  if (!queued) fail("Transactional outbox unavailable", 503);
  return correction;
}
export async function applyCategoryConversion(tx, env, row) {
  await tx.$queryRaw`SELECT id FROM "EmployeeCategoryConversion" WHERE "tenantId"=${env.tenantId}::uuid AND id=${row.id}::uuid FOR UPDATE`;
  row = await tx.employeeCategoryConversion.findUnique({
    where: { id: row.id },
  });
  if (row.state !== "APPROVED" || row.effectiveAt > env.now) return row;
  const current = await employee(tx, env.tenantId, row.employeeCode);
  await tx.$queryRaw`SELECT id FROM "Employee" WHERE id=${current.id} FOR UPDATE`;
  const newCode = await allocateEmployeeCode(tx, env.tenantId, row.category);
  await propagateEmployeeCode(tx, {
    tenantId: env.tenantId,
    oldCode: row.employeeCode,
    newCode,
    actorCode: row.approvedByCode,
    reason: row.reason,
    effectiveAt: row.effectiveAt,
    conversionRef: row.id,
  });
  await tx.employee.update({
    where: { id: current.id },
    data: { employeeCategory: row.category, version: { increment: 1 } },
  });
  return tx.employeeCategoryConversion.update({
    where: { id: row.id },
    data: { state: "APPLIED", newCode, version: { increment: 1 } },
  });
}
export const convertCategory = (raw) => {
  const input = CategoryConversion.parse(raw);
  return run(
    input,
    "hr.employee_code.manage",
    async (tx, env) => {
      const e = await employee(tx, env.tenantId, input.employeeCode);
      let row;
      await tx.$queryRaw`SELECT id FROM "Employee" WHERE id=${e.id} FOR UPDATE`;
      if (input.action === "REQUEST") {
        checkVersion(
          await employee(tx, env.tenantId, input.employeeCode),
          input.expectedVersion,
        );
        if (input.category === e.employeeCategory)
          fail("Choose a different category");
        if (
          new Date(input.effectiveAt) <
          new Date(env.now.toISOString().slice(0, 10))
        )
          fail("Conversion cannot be backdated");
        if (
          await tx.employeeCategoryConversion.findFirst({
            where: {
              tenantId: env.tenantId,
              employeeCode: e.employee_code,
              state: { in: ["REQUESTED", "APPROVED"] },
            },
          })
        )
          fail("An open conversion already exists", 409);
        row = await tx.employeeCategoryConversion.create({
          data: {
            tenantId: env.tenantId,
            employeeCode: e.employee_code,
            category: input.category,
            effectiveAt: new Date(input.effectiveAt),
            reason: input.reason,
            requestedByCode: env.who.employee_code,
          },
        });
      } else {
        row = await tx.employeeCategoryConversion.findFirst({
          where: {
            tenantId: env.tenantId,
            id: input.conversionRef,
            employeeCode: e.employee_code,
          },
        });
        if (!row) fail("Conversion not found", 404);
        checkVersion(row, input.expectedVersion);
        if (row.state !== "REQUESTED") fail("Conversion already decided", 409);
        if (
          [row.employeeCode, row.requestedByCode].includes(
            env.who.employee_code,
          )
        )
          fail(
            "Another authorized HR officer must approve the conversion",
            403,
          );
        await consumeApproval(tx, env.tenantId, "CATEGORY_CONVERSION", row.id, input.action === "APPROVE");
        row = await tx.employeeCategoryConversion.update({
          where: { id: row.id },
          data: {
            state: input.action === "APPROVE" ? "APPROVED" : "REJECTED",
            approvedByCode: env.who.employee_code,
            reason: row.reason + "\nDecision: " + input.reason,
            version: { increment: 1 },
          },
        });
        row = await applyCategoryConversion(tx, env, row);
      }
      return result(
        env,
        view(row, "CATEGORY_CONVERSION", {
          category: row.category,
          newCode: row.newCode,
          effectiveAt: row.effectiveAt,
          reason: row.reason,
          requestedByCode: row.requestedByCode,
          approvedByCode: row.approvedByCode,
        }),
      );
    },
    "CATEGORY_CONVERSION",
  );
};

export const employeeCodeStatus = (raw) =>
  run(
    raw,
    "hr.employee_code.manage",
    async (tx, env) => {
      const e = await employee(tx, env.tenantId, raw.employeeCode);
      const conversions = await tx.employeeCategoryConversion.findMany({
        where: { tenantId: env.tenantId, employeeCode: e.employee_code },
        orderBy: { createdAt: "desc" },
      });
      const format = await tx.employeeCodeConfiguration.findUnique({
        where: { tenantId: env.tenantId },
      });
      return result(
        env,
        view(
          {
            id: env.tenantId,
            employeeCode: e.employee_code,
            version: e.version,
            createdAt: e.created_at,
            updatedAt: e.updated_at,
          },
          "EMPLOYEE_IDENTITY",
          {
            category: e.employeeCategory,
            format: format
              ? {
                  padding: format.padding,
                  separator: format.separator,
                  version: format.version,
                }
              : { padding: 4, separator: "-", version: 0 },
          },
        ),
        conversions.map((c) =>
          view(c, "CATEGORY_CONVERSION", {
            category: c.category,
            effectiveAt: c.effectiveAt,
            requestedByCode: c.requestedByCode,
            newCode: c.newCode,
            reason: c.reason,
          }),
        ),
      );
    },
    "CODE_STATUS",
  );
