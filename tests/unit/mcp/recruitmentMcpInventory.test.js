const collect = (register) => {
  const tools = [],
    resources = [];
  register({
    tool: (n) => tools.push(n),
    registerTool: (n) => tools.push(n),
    resource: (n) => resources.push(n),
  });
  return { tools, resources };
};
const collected = new Map(registrars.map(([name, register]) => [name, collect(register)]));
const allRecruitmentTools = [...collected.values()].flatMap((c) => c.tools);
describe("Recruitment and onboarding MCP inventory", () => {
  it("registers exactly the pinned 271 tools", () => {
    expect([...allRecruitmentTools].sort()).toEqual(EXPECTED_TOOLS);
    expect(EXPECTED_TOOLS).toHaveLength(271);
  });
  it("matches the shared gateway catalogue exactly", () => {
    expect(Object.keys(RECRUITMENT_TOOLS).sort()).toEqual(EXPECTED_TOOLS);
    for (const entry of Object.values(RECRUITMENT_TOOLS)) {
      for (const permission of [entry.permission].flat()) expect(permission).toMatch(/^hr[.]/);
      expect(["read", "write", "heavy"]).toContain(entry.rateClass);
    }
  });
  it("pins per-module registration counts", () => {
    expect(Object.fromEntries([...collected].map(([k, v]) => [k, v.tools.length]))).toEqual(
      EXPECTED_PER_MODULE,
    );
    expect(Object.values(EXPECTED_PER_MODULE).reduce((a, b) => a + b, 0)).toBe(271);
  });
  it("has no duplicate name across the recruitment modules or complete HR registry", () => {
    expect(new Set(allRecruitmentTools).size).toBe(271);
    const all = collect(registerAllTools).tools;
    expect(new Set(all).size).toBe(all.length);
    for (const name of EXPECTED_TOOLS) expect(all).toContain(name);
  });
  it("registers every privacy operation as a permissioned tool", () => {
    const privacy = EXPECTED_TOOLS.filter((n) =>
      /consent|dnc|legal_hold|retention|anonymize|request_/.test(n),
    );
    expect(privacy).toHaveLength(16);
    for (const name of privacy) expect(allRecruitmentTools).toContain(name);
  });
  it("keeps the tags resource distinct from executable tools", () => {
    expect(collected.get("recruitmentTools").resources).toContain("hr_recruitment_tags_list");
    expect(allRecruitmentTools).not.toContain("hr_recruitment_tags_list");
  });
});
