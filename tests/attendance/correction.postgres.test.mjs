import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { setup, db, as, people, company, other, prisma, submit, act } from '../approval/fixtures.mjs';
import { saveCorrectionRequest, myCorrectionRequests } from '../../src/services/attendanceCorrectionRequest.service.js';
import { enterRuleTime, listRuleCases, employeeCodeOptions } from '../../src/services/attendanceRules.service.js';
import { listCheckInOuts } from '../../src/services/timesheetReport.service.js';
import { applyEvaluatedShifts } from '../../src/services/attendanceWriter.service.js';
import { replayTenant } from '../../src/lib/attendanceReplay.js';

test('employee drafts, immutable evidence, concurrency and final missing-time application', async t => {
  await setup();
  const date = '2026-02-12';
  const [session] = await db(tx => replayTenant({ tenantId: company, employeeIds: [people.EMPLOYEE.id], from: date, to: date, db: tx, includeEmpty: true }));
  const input = { id: randomUUID(), version: 0, date, sessionKey: session.sessionKey, checkIn: '09:00:01', checkOut: '17:00:00', reason: 'Reader missed the recorded arrival', evidence: 'TEST-REGISTER-012: supervised arrival and departure record', reasonCategory:'MISSED_PUNCH',evidenceDate:date };
  await assert.rejects(enterRuleTime({ user: { tenantId: company, roles: ['HR Manager'] } }), e => e.status === 410);
  await assert.rejects(as('EMPLOYEE', () => saveCorrectionRequest({ ...input, checkOut: '23:00:00' })), /cutoff/);
  let draft = await as('EMPLOYEE', () => saveCorrectionRequest({...input,checkIn:null,checkOut:null,reason:'',evidence:'',reasonCategory:null,evidenceDate:null}));
  await assert.rejects(submit({kind:'ATTENDANCE_CORRECTION',ref:draft.id}), /Complete the supported missing time/);
  draft = await as('EMPLOYEE', () => saveCorrectionRequest({...input,version:draft.version}));
  assert.equal((await db(tx => tx.attendanceManualTime.count({ where: { tenantId: company } }))), 0);
  assert.equal((await as('EMPLOYEE', () => saveCorrectionRequest(input))).id, draft.id);
  await assert.rejects(as('OTHER', () => saveCorrectionRequest({ ...input, version: draft.version })), /not found/);
  await assert.rejects(as('EMPLOYEE', () => saveCorrectionRequest({ ...input, id: randomUUID() })), /already exists/);
  await assert.rejects(as('EMPLOYEE', () => saveCorrectionRequest(input), other), /linked employee/);
  let request = await submit({ kind: 'ATTENDANCE_CORRECTION', ref: draft.id });
  await assert.rejects(as('EMPLOYEE', () => saveCorrectionRequest({ ...input, version: draft.version, reason: 'Different fact' })), /under review/);
  request = await act('MANAGER', request, 'REVERT');
  draft = await as('EMPLOYEE', () => saveCorrectionRequest({ ...input, version: draft.version, evidence: input.evidence + ' verified against original' }));
  assert.equal((await as('EMPLOYEE', () => myCorrectionRequests({ date }))).items[0].canEdit, true);
  request = await submit({ kind: 'ATTENDANCE_CORRECTION', ref: draft.id }, request.version);
  request = await act('MANAGER', request, 'RECOMMEND_APPROVAL');
  request = await act('HR', request, 'VERIFY');
  request = await act('MANAGEMENT', request, 'REVERT');
  assert.equal(request.stage, 'HR');
  request = await act('HR', request, 'VERIFY');
  request = await act('MANAGEMENT', request, 'APPROVE');
  assert.equal(request.execution, 'APPLIED');
  const marks = await db(tx => tx.attendanceManualTime.findMany({ where: { tenantId: company, employeeId: people.EMPLOYEE.id } }));
  assert.equal(marks.length, 2);
  assert.equal(marks.find(p => p.direction === 'IN').timestamp.toISOString(), date + 'T09:00:01.000Z');
  assert.ok(marks.every(p => p.actorId === people.MANAGEMENT.employee_code));
  const attendance = await db(tx => tx.attendance.findFirst({ where: { tenantId: company, employeeId: people.EMPLOYEE.id, date: new Date(date) } }));
  assert.equal(attendance.status, 'LATE');
  const daily = await as('HR',()=>listCheckInOuts({tenantId:company,from:date,to:date,q:people.EMPLOYEE.employee_code}));
  assert.deepEqual(daily.items[0].correctionRequests,[{reference:draft.id,stage:'APPROVED'}]);
  await db(tx=>tx.employee.createMany({data:['0EMP-EMPLOYEE','EMP-EMPLOYEE-SUFFIX'].map(employee_code=>({tenant_id:company,employee_code,employeeCategory:'EMPLOYEE',first_name:'Synthetic',hire_date:new Date('2026-01-01')}))}));
  const optionArgs={user:{tenantId:company,roles:['HR Manager']},q:'EMP-EMPLOYEE',pageSize:1};
  const first=await db(tx=>employeeCodeOptions({...optionArgs,page:1},tx));
  const second=await db(tx=>employeeCodeOptions({...optionArgs,page:2},tx));
  const third=await db(tx=>employeeCodeOptions({...optionArgs,page:3},tx));
  assert.equal(first.total,3);
  assert.deepEqual([first,second,third].map(page=>page.items[0].code),['EMP-EMPLOYEE','0EMP-EMPLOYEE','EMP-EMPLOYEE-SUFFIX']);
  await t.test('new evaluation blocks stale approval without partial effects', async () => {
    const day = '2026-02-13';
    const [s] = await db(tx => replayTenant({ tenantId: company, employeeIds: [people.EMPLOYEE.id], from: day, to: day, db: tx, includeEmpty: true }));
    const source = await as('EMPLOYEE', () => saveCorrectionRequest({ ...input, id: randomUUID(), date: day, sessionKey: s.sessionKey }));
    let r = await submit({ kind: 'ATTENDANCE_CORRECTION', ref: source.id });
    r = await act('MANAGER', r, 'RECOMMEND_APPROVAL'); r = await act('HR', r, 'VERIFY');
    await db(tx => applyEvaluatedShifts({ tenantId: company, employeeIds: [people.EMPLOYEE.id], from: day, to: day, db: tx, dryRun: false }));
    await assert.rejects(act('MANAGEMENT', r, 'APPROVE'), /Attendance changed/);
    assert.equal((await db(tx => tx.hrApprovalRequest.findFirst({ where: { tenantId: company, id: r.approvalRef } }))).stage, 'MANAGEMENT');
    assert.equal(await db(tx => tx.attendanceManualTime.count({ where: { tenantId: company, date: new Date(day) } })), 0);
  });
  const cases = await as('HR', () => listRuleCases({ user: { tenantId: company, roles: ['HR Manager'] }, from: '2026-02-01', to: '2026-02-28', q: 'EMP-EMPLOYEE', category: 'late', pageSize: 1 }));
  assert.equal(cases.total, cases.summary.late);
  assert.equal(cases.summary.total, cases.total);
  assert.ok(cases.items.every(row => row.type === 'LATE_CHECKIN' && row.employee.employee_code === 'EMP-EMPLOYEE'));
}).finally(() => prisma.$disconnect());
